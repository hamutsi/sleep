function alcSig(p) {
  const bits = [];
  if (p.rhr != null) bits.push(`דופק המנוחה הלילה ${num(p.rhr)} לעומת ${num(p.rhrBase)} בממוצע`);
  if (p.hrv != null) bits.push(`ה-HRV ${num(p.hrv)} לעומת ${num(p.hrvBase)}`);
  return bits.length ? ` בשעון: ${bits.join(', ')}.` : '';
}

