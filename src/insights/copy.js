// ימים 5 עד 7 של מיקוד: אחרי ארבע הגרסאות הייחודיות, כרטיסי התקדמות קצרים, כדי שהנוסח לא יחזור על עצמו בתוך השבוע
export function renderMove(key, params, day) {
  const p = { ...(params || {}), d: day };
  if (day <= 4) { const t = render(key, p, day - 1); return t && { ...t, variant: day - 1 }; }
  const name = FOCUS_NAME[key] || 'המיקוד';
  const left = Math.max(0, 7 - day);
  const list = [
    () => ({ title: `יום ${day} במיקוד: ${name}`, body: 'חלק מהדרך מאחורינו. אם היה יום שלא הצליח, לא מתחילים מחדש אלא ממשיכים מהיום.' }),
    () => ({ title: `${left === 1 ? 'עוד יום אחד' : `עוד ${left} ימים`} במיקוד`, body: `המיקוד "${name}" נמשך. בסוף השבוע אפשר להשוות את הנתונים של ימי המיקוד לשבוע שלפניו.` }),
    () => ({ title: 'היום האחרון במיקוד', body: `מחר בוחרים מיקוד חדש, או ממשיכים עם "${name}" אם הוא עבד. שינוי קטן שנשאר שווה יותר משינוי גדול שנעלם אחרי יומיים.` }),
  ];
  const i = Math.min(2, Math.max(0, day - 5));
  return { ...list[i](), variant: 4 + i };
}

const isBanded = (t) => t && !Array.isArray(t);
export function variantsOf(key, p = {}) {
  if (key === 'quiet:stable') return QUIET;
  const t = LOOK[key] || DISC[key] || MOVE[key];
  if (!t) return [];
  return isBanded(t) ? t[p.band] || [] : t;
}
export const variantCount = (key, p) => variantsOf(key, p).length;

// מחזיר { title, body } לפי מפתח, פרמטרים ומספר גרסה
export function render(key, params, variant = 0) {
  const list = variantsOf(key, params);
  if (!list.length) return null;
  return list[((variant % list.length) + list.length) % list.length](params || {});
}

